class StationSupplierFormDialog extends StatefulWidget {
  final SupplierModel? supplier;
  const StationSupplierFormDialog({super.key, this.supplier});

  @override
  State<StationSupplierFormDialog> createState() => _StationSupplierFormDialogState();
}

class _StationSupplierFormDialogState extends State<StationSupplierFormDialog> {
  final _formKey = GlobalKey<FormState>();
  final _codeCtrl = TextEditingController();
  final _nameCtrl = TextEditingController();
  final _phoneCtrl = TextEditingController();
  final _addressCtrl = TextEditingController();
  final _initialBalanceCtrl = TextEditingController(text: '0.00');

  String _currency = 'EGP';
  String _direction = 'CREDIT';
  List<String> _selectedServices = [];
  bool _isSaving = false;
  bool _isLoadingCode = false;
  bool _isLoadingServices = true;

  List<String> _operationalServices = List<String>.from(CostCategoryService.stationSupplierCategories);

  @override
  void initState() {
    super.initState();
    if (widget.supplier != null) {
      final s = widget.supplier!;
      _codeCtrl.text = s.supplierCode;
      _nameCtrl.text = s.name;
      _phoneCtrl.text = s.phone;
      _addressCtrl.text = s.address;
      _initialBalanceCtrl.text = s.initialBalance == 0.0 ? '0.00' : s.initialBalance.toString();
      _direction = s.initialBalanceDirection.isNotEmpty ? s.initialBalanceDirection : 'CREDIT';
      _currency = 'EGP';
      _selectedServices = List<String>.from(s.categories);
    } else {
      _loadAutoGeneratedCode();
    }
    _loadOperationalServices();
  }

  Future<void> _loadOperationalServices() async {
    try {
      final services = await CostCategoryService().getStationCategories();
      if (mounted) {
        setState(() {
          _operationalServices = services;
          _isLoadingServices = false;
          // Automatically determine and pre-select all registered operational services when creating a new supplier or if empty
          if (widget.supplier == null || _selectedServices.isEmpty) {
            _selectedServices = List<String>.from(services);
          }
        });
      }
    } catch (_) {
      if (mounted) {
        setState(() {
          _isLoadingServices = false;
          if (widget.supplier == null || _selectedServices.isEmpty) {
            _selectedServices = List<String>.from(_operationalServices);
          }
        });
      }
    }
  }

  @override
  void dispose() {
    _codeCtrl.dispose();
    _nameCtrl.dispose();
    _phoneCtrl.dispose();
    _addressCtrl.dispose();
    _initialBalanceCtrl.dispose();
    super.dispose();
  }

  Future<void> _loadAutoGeneratedCode() async {
    setState(() => _isLoadingCode = true);
    try {
      final code = await SupplierDao().generateNextCode(supplierType: 'station');
      if (mounted) {
        setState(() {
          _codeCtrl.text = code.replaceAll('SUPP-', '');
          _isLoadingCode = false;
        });
      }
    } catch (_) {
      if (mounted) {
        setState(() {
          _codeCtrl.text = '85001';
          _isLoadingCode = false;
        });
      }
    }
  }

  Future<void> _save() async {
    if (!ReadOnlyGuard.check(context)) return;
    if (!_formKey.currentState!.validate()) return;

    final codeText = _codeCtrl.text.trim();
    final codeValidation = SupplierModel.validateSupplierCode(codeText, 'station');
    if (codeValidation != null) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(codeValidation, style: const TextStyle(fontFamily: 'Cairo')),
          backgroundColor: AppTheme.danger,
        ),
      );
      return;
    }

    final exists = await SupplierDao().checkCodeExists(codeText, excludeId: widget.supplier?.id);
    if (exists) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('كود المورد ($codeText) مستخدم بالفعل، يرجى اختيار كود آخر في النطاق 85000 - 89999',
              style: const TextStyle(fontFamily: 'Cairo')),
          backgroundColor: AppTheme.danger,
        ),
      );
      return;
    }

    setState(() => _isSaving = true);
    try {
      final initialBal = double.tryParse(_initialBalanceCtrl.text.trim()) ?? 0.0;
      final masterAccountId = await SupplierDao().resolveMasterAccountId('station', code: codeText);

      final supplierData = SupplierModel(
        id: widget.supplier?.id,
        supplierCode: codeText,
        name: _nameCtrl.text.trim(),
        phone: _phoneCtrl.text.trim(),
        address: _addressCtrl.text.trim(),
        supplierType: 'station',
        accountId: masterAccountId,
        categories: _selectedServices,
        initialBalance: initialBal,
        initialBalanceDirection: _direction,
        currency: _currency,
        outstandingBalance: widget.supplier == null
            ? initialBal
            : (widget.supplier!.outstandingBalance + (initialBal - widget.supplier!.initialBalance)),
      );

      if (widget.supplier == null) {
        await SupplierDao().insert(supplierData);
      } else {
        await SupplierDao().update(supplierData);
      }

      DataChangeEventBus.instance.notifySuppliersChanged();

      if (mounted) {
        Navigator.pop(context, true);
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Directionality(
              textDirection: TextDirection.rtl,
              child: Row(
                children: [
                  const Icon(Icons.check_circle_rounded, color: Colors.white, size: 22),
                  const SizedBox(width: 8),
                  Expanded(
                    child: Text(
                      widget.supplier == null
                          ? 'تم إضافة مورد المحطة بنجاح وربطه بحساب 21117'
                          : 'تم حفظ تعديلات مورد المحطة بنجاح',
                      style: const TextStyle(fontFamily: 'Cairo', fontWeight: FontWeight.bold),
                    ),
                  ),
                ],
              ),
            ),
            backgroundColor: AppTheme.success,
          ),
        );
      }
    } catch (e) {
      if (mounted) {
        setState(() => _isSaving = false);
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('خطأ أثناء الحفظ: $e', style: const TextStyle(fontFamily: 'Cairo')),
            backgroundColor: AppTheme.danger,
          ),
        );
      }
    }
  }

