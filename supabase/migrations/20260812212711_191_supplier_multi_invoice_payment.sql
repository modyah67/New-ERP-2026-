BEGIN;

-- 1. Create the payment allocations table
CREATE TABLE IF NOT EXISTS public.supplier_payment_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type TEXT NOT NULL CHECK (source_type IN ('treasury', 'bank')),
    source_id BIGINT NOT NULL,
    purchase_invoice_id INTEGER NOT NULL REFERENCES public.purchase_invoices(id) ON DELETE CASCADE,
    amount NUMERIC NOT NULL CHECK (amount > 0),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    created_by UUID REFERENCES auth.users(id) DEFAULT auth.uid()
);

-- 2. Create the unified RPC for auto-allocation payment
CREATE OR REPLACE FUNCTION public.rpc_supplier_multi_payment(
    p_source_type          TEXT, -- 'treasury' or 'bank'
    p_source_id            BIGINT, -- treasury_id or bank_account_id
    p_currency             TEXT,
    p_amount               NUMERIC,
    p_supplier_id          UUID,
    p_description          TEXT,
    p_notes                TEXT,
    p_expense_account_id   INTEGER DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
    v_tx_id BIGINT;
    v_je_id BIGINT;
    v_total_unpaid NUMERIC := 0;
    v_remaining_to_allocate NUMERIC := p_amount;
    v_invoice RECORD;
    v_alloc_amount NUMERIC;
    v_res JSONB;
BEGIN
    IF p_amount <= 0 THEN
        RAISE EXCEPTION 'مبلغ السداد يجب أن يكون أكبر من صفر';
    END IF;

    -- Calculate total unpaid amount for the supplier
    SELECT COALESCE(SUM(GREATEST(0, (COALESCE(total_amount, 0) - COALESCE(discount_amount, 0)) - COALESCE(paid_amount, 0))), 0)
    INTO v_total_unpaid
    FROM public.purchase_invoices
    WHERE supplier_id = p_supplier_id
      AND payment_status IN ('unpaid', 'partial');

    IF p_amount > v_total_unpaid THEN
        RAISE EXCEPTION 'مبلغ السداد (%) أكبر من إجمالي الفواتير المستحقة للمورد (%)', p_amount, v_total_unpaid;
    END IF;

    -- Deduct from source and create main transaction using EXISTING logic
    IF p_source_type = 'treasury' THEN
        -- spend_custody handles creating the journal entry and treasury transaction
        -- We pass reference_type = 'multi_invoice' so it doesn't update any single invoice
        v_tx_id := public.spend_custody(
            p_treasury_id := p_source_id,
            p_currency := p_currency,
            p_amount := p_amount,
            p_description := p_description,
            p_customer_id := NULL,
            p_supplier_id := p_supplier_id,
            p_clearing_agent_id := NULL,
            p_shipping_company_id := NULL,
            p_shareholder_id := NULL,
            p_expense_account_id := p_expense_account_id,
            p_reference_type := 'multi_invoice',
            p_reference_id := NULL,
            p_notes := p_notes
        );
        
        -- Get journal_entry_id from the newly created transaction
        SELECT journal_entry_id INTO v_je_id 
        FROM public.treasury_transactions 
        WHERE id = v_tx_id;

    ELSIF p_source_type = 'bank' THEN
        -- withdraw_bank_account handles creating the journal entry and bank transaction
        v_res := public.withdraw_bank_account(
            p_account_id := p_source_id::INTEGER,
            p_amount := p_amount,
            p_description := p_description,
            p_entity_type := 'supplier',
            p_entity_id := p_supplier_id::TEXT,
            p_counterparty_name := NULL,
            p_expense_account_id := p_expense_account_id,
            p_notes := p_notes
        );
        v_tx_id := (v_res->>'transaction_id')::BIGINT;
        v_je_id := (v_res->>'journal_entry_id')::BIGINT;

    ELSE
        RAISE EXCEPTION 'نوع مصدر الأموال غير مدعوم: %', p_source_type;
    END IF;

    -- Auto-allocate to unpaid invoices from oldest to newest
    FOR v_invoice IN 
        SELECT id, 
               GREATEST(0, (COALESCE(total_amount, 0) - COALESCE(discount_amount, 0)) - COALESCE(paid_amount, 0)) AS remaining_amount
        FROM public.purchase_invoices
        WHERE supplier_id = p_supplier_id
          AND payment_status IN ('unpaid', 'partial')
        ORDER BY purchase_date ASC, created_at ASC
    LOOP
        IF v_remaining_to_allocate <= 0 THEN
            EXIT; -- Done allocating
        END IF;

        IF v_invoice.remaining_amount > 0 THEN
            v_alloc_amount := LEAST(v_invoice.remaining_amount, v_remaining_to_allocate);

            -- Insert allocation record
            INSERT INTO public.supplier_payment_allocations(
                source_type, source_id, purchase_invoice_id, amount
            ) VALUES (
                p_source_type, v_tx_id, v_invoice.id, v_alloc_amount
            );

            -- Update purchase invoice
            UPDATE public.purchase_invoices
            SET paid_amount = COALESCE(paid_amount, 0) + v_alloc_amount,
                remaining_amount = GREATEST(0, (COALESCE(total_amount, 0) - COALESCE(discount_amount, 0)) - (COALESCE(paid_amount, 0) + v_alloc_amount)),
                payment_status = CASE
                    WHEN GREATEST(0, (COALESCE(total_amount, 0) - COALESCE(discount_amount, 0)) - (COALESCE(paid_amount, 0) + v_alloc_amount)) <= 0.001 THEN 'paid'
                    ELSE 'partial'
                END,
                updated_at = NOW()
            WHERE id = v_invoice.id;

            -- Decrease remaining amount to allocate
            v_remaining_to_allocate := v_remaining_to_allocate - v_alloc_amount;
        END IF;
    END LOOP;

    RETURN jsonb_build_object(
        'success', true,
        'transaction_id', v_tx_id,
        'journal_entry_id', v_je_id
    );
END;
$$;

COMMIT;
